def team_t(key: str, lang: str = "uz", **kwargs) -> str:
    code = normalize_lang(lang)
    text = (TEAM_I18N.get(code) or {}).get(key)
    if text is None:
        text = _UZ.get(key)
    if text is None:
        return safe_t(key, code, **kwargs)
    try:
        return text.format(**kwargs) if kwargs else text
    except Exception:  # pragma: no cover — format himoyasi
        return text


def team_parity_report(langs=("uz", "ru", "en")) -> dict:
    from locales.translations import format_args

    base = set(TEAM_I18N["uz"])
    missing, format_mismatch = {}, {}
    for code in langs:
        table = TEAM_I18N[code]
        missing[code] = sorted(base - set(table))
        for key in base & set(table):
            if format_args(TEAM_I18N["uz"][key]) != format_args(table[key]):
                format_mismatch.setdefault(code, []).append(key)
    return {"keys": len(base), "missing": missing, "format_mismatch": format_mismatch,
            "in_sync": not any(missing.values()) and not format_mismatch}
